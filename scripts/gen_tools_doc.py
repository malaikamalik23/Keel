"""Generate docs/TOOLS.md from the live tool registry, so the documentation can never drift from the code.

    python -m scripts.gen_tools_doc          # rewrite docs/TOOLS.md
    python -m scripts.gen_tools_doc --check  # exit 1 if it is out of date (used by the test suite)
"""
from __future__ import annotations

import sys
from pathlib import Path

from app.tools.groups import GROUP_INFO, group_of
from evals.common import full_registry

OUT = Path(__file__).resolve().parents[1] / "docs" / "TOOLS.md"
TIERS = [
    ("read", "READ: runs immediately"),
    ("write", "WRITE: runs immediately and is audited; needs your approval if the session is tainted by external content (or `CONFIRM_WRITES=true`)"),
    ("high_impact", "HIGH IMPACT: never runs from the model; queued until you approve it in the dashboard or CLI"),
]


def render() -> str:
    tools = full_registry().all()
    lines = [
        "# Tool reference", "",
        "_Generated by `python -m scripts.gen_tools_doc` from the tool registry. Do not edit by hand._", "",
        f"Keel has **{len(tools)} tools**. In the default `TOOL_PROFILE=lean`, each request carries only the core `tasks` group plus the groups the "
        "message needs (matched by keywords, kept on while recently used, or pulled in by the model with `load_tools`), about 3k tokens instead of 7k. "
        "`TOOL_PROFILE=full` sends everything. Permissions and confirmation apply to every call whether or not the tool was advertised. Tools marked 🌐 return text written by third parties; their output is fenced as "
        "untrusted data and taints the session (see [SECURITY.md](../SECURITY.md)). Tools marked ⚙️ are only advertised when configured.", "",
    ]
    optional = {"read_calendar", "web_fetch", "web_search", "notes_search", "read_note"} | {t.name for t in tools if t.name.startswith("github_")}
    for key, title in TIERS:
        group = [t for t in tools if t.permission.value == key]
        lines += [f"## {title}", "", "| Tool | Group | What it's for |", "|---|---|---|"]
        for t in group:
            flags = (" 🌐" if t.returns_untrusted else "") + (" ⚙️" if t.name in optional else "")
            desc = " ".join(t.description.split()).replace("|", "\\|")
            lines.append(f"| `{t.name}`{flags} | {group_of(t.name)} | {desc} |")
        lines.append("")
    lines += ["## Tool groups", "", "| Group | Contents |", "|---|---|"] + [f"| `{g}` | {d.split(': ', 1)[1]} |" for g, d in GROUP_INFO.items()] + [""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
